const u8* glyphRows(char c) {
  const i32 code = static_cast<i32>(static_cast<unsigned char>(c));
  if (code < 32 || code > 126) return kUnknown;
  return kGlyphs[code - 32];
}

i32 textWidth(const std::string& text, i32 scale) {
  if (text.empty() || scale <= 0) return 0;
  const i32 count = static_cast<i32>(text.size());
  return (count * kGlyphAdvance - 1) * scale;
}

i32 drawText(Image& image, i32 x, i32 y, const std::string& text, const Vec3& color, i32 scale) {
  if (image.isEmpty() || scale <= 0) return 0;
  const u8 r = toByte(color.x);
  const u8 g = toByte(color.y);
  const u8 b = toByte(color.z);
  i32 penX = x;
  i32 drawn = 0;
  for (const char c : text) {
    const u8* rows = glyphRows(c);
    for (i32 row = 0; row < kGlyphHeight; ++row) {
      const u8 mask = rows[row];
      for (i32 col = 0; col < kGlyphWidth; ++col) {
        if ((mask & (1U << (kGlyphWidth - 1 - col))) == 0U) continue;
        for (i32 sy = 0; sy < scale; ++sy) {
          for (i32 sx = 0; sx < scale; ++sx) {
            putPixel(image, penX + col * scale + sx, y + row * scale + sy, r, g, b);
          }
        }
      }
    }
    penX += kGlyphAdvance * scale;
    ++drawn;
  }
  return drawn;
}

void fillRect(Image& image, i32 x, i32 y, i32 width, i32 height, const Vec3& color, f64 alpha) {
  if (image.isEmpty() || width <= 0 || height <= 0) return;
  const f64 a = alpha < 0.0 ? 0.0 : (alpha > 1.0 ? 1.0 : alpha);
  const u8 r = toByte(color.x);
  const u8 g = toByte(color.y);
  const u8 b = toByte(color.z);
  const i32 x0 = std::max(0, x);
  const i32 y0 = std::max(0, y);
  const i32 x1 = std::min(image.width, x + width);
  const i32 y1 = std::min(image.height, y + height);
  for (i32 py = y0; py < y1; ++py) {
    for (i32 px = x0; px < x1; ++px) blendPixel(image, px, py, r, g, b, a);
  }
}

void drawBar(Image& image, i32 x, i32 y, i32 width, i32 height, f64 fraction, const Vec3& fill, const Vec3& back) {
  if (width <= 0 || height <= 0) return;
  const f64 f = fraction < 0.0 ? 0.0 : (fraction > 1.0 ? 1.0 : fraction);
  const i32 filled = static_cast<i32>(std::lround(f * static_cast<f64>(width)));
  fillRect(image, x, y, width, height, back, 1.0);
  if (filled > 0) fillRect(image, x, y, filled, height, fill, 1.0);
}

