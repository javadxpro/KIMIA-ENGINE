// A hollow box for anything outside 32..126 (e.g. UTF-8 bytes): visible, not silent.
constexpr u8 kUnknown[7] = {0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F};

u8 toByte(f64 value) {
  const f64 clamped = value < 0.0 ? 0.0 : (value > 1.0 ? 1.0 : value);
  return static_cast<u8>(std::lround(clamped * 255.0));
}

void putPixel(Image& image, i32 x, i32 y, u8 r, u8 g, u8 b) {
  if (x < 0 || y < 0 || x >= image.width || y >= image.height) return;
  u8* pixel = image.at(x, y);
  pixel[0] = r;
  if (image.channels > 1) pixel[1] = g;
  if (image.channels > 2) pixel[2] = b;
}

void blendPixel(Image& image, i32 x, i32 y, u8 r, u8 g, u8 b, f64 alpha) {
  if (x < 0 || y < 0 || x >= image.width || y >= image.height) return;
  u8* pixel = image.at(x, y);
  const f64 keep = 1.0 - alpha;
  pixel[0] = static_cast<u8>(std::lround(static_cast<f64>(pixel[0]) * keep + static_cast<f64>(r) * alpha));
  if (image.channels > 1) pixel[1] = static_cast<u8>(std::lround(static_cast<f64>(pixel[1]) * keep + static_cast<f64>(g) * alpha));
  if (image.channels > 2) pixel[2] = static_cast<u8>(std::lround(static_cast<f64>(pixel[2]) * keep + static_cast<f64>(b) * alpha));
}

